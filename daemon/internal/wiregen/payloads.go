package wiregen

import (
	"encoding/json"
	"fmt"
	"reflect"
	"sort"
	"strings"
	"time"

	"github.com/cavi-ai/secure-agent/daemon/internal/api"
	"github.com/cavi-ai/secure-agent/daemon/internal/apiroutes"
)

// RoutePayload is one typed route's response as encoding/json writes it:
// Full with every field populated, Empty as the zero value.
type RoutePayload struct {
	Path        string
	Full, Empty []byte
}

// RoutePayloads returns a payload for every route and leaf in apiroutes.Table
// that declares a response type, ordered by path. Leaf paths read
// "/prefix/{id}/leaf".
func RoutePayloads() ([]RoutePayload, error) {
	types := map[string]reflect.Type{}
	for _, v := range api.RouteWireTypes() {
		t := reflect.TypeOf(v).Elem()
		types[t.String()] = t
	}
	var out []RoutePayload
	add := func(path, response string) error {
		if response == "" {
			return nil
		}
		t, ok := types[response]
		if !ok {
			return fmt.Errorf("%s: response %q is not a route wire type", path, response)
		}
		full, err := json.Marshal(sample(t, map[reflect.Type]bool{}).Interface())
		if err != nil {
			return fmt.Errorf("%s: %w", path, err)
		}
		empty, err := json.Marshal(reflect.New(t).Elem().Interface())
		if err != nil {
			return fmt.Errorf("%s: %w", path, err)
		}
		out = append(out, RoutePayload{Path: path, Full: full, Empty: empty})
		return nil
	}
	for _, r := range apiroutes.Table {
		if err := add(r.Path, r.Response); err != nil {
			return nil, err
		}
		for _, leaf := range r.Leaves {
			if err := add(r.Path+"{id}/"+leaf.Path, leaf.Response); err != nil {
				return nil, err
			}
		}
	}
	sort.Slice(out, func(i, j int) bool { return out[i].Path < out[j].Path })
	return out, nil
}

var sampleTime = time.Date(2026, 1, 2, 3, 4, 5, 123456789, time.UTC)

// sample fills every exported field, one element per slice and one entry per
// map, so the encoded value carries every key the type can emit. A struct
// already being filled on the current path stops recursion: slices and maps
// of it stay empty, arrays zero and pointers nil.
func sample(t reflect.Type, filling map[reflect.Type]bool) reflect.Value {
	v := reflect.New(t).Elem()
	switch t.Kind() {
	case reflect.Pointer:
		if !recurses(t.Elem(), filling) {
			v.Set(sample(t.Elem(), filling).Addr())
		}
	case reflect.Struct:
		if t == timeType {
			v.Set(reflect.ValueOf(sampleTime))
			return v
		}
		filling[t] = true
		defer delete(filling, t)
		for i := 0; i < t.NumField(); i++ {
			if v.Field(i).CanSet() {
				v.Field(i).Set(sample(t.Field(i).Type, filling))
			}
		}
	case reflect.Slice:
		switch {
		case t.Elem().Kind() == reflect.Uint8:
			v.SetBytes([]byte("{}"))
		case recurses(t.Elem(), filling):
			v.Set(reflect.MakeSlice(t, 0, 0))
		default:
			v.Set(reflect.Append(v, sample(t.Elem(), filling)))
		}
	case reflect.Array:
		if !recurses(t.Elem(), filling) {
			for i := 0; i < t.Len(); i++ {
				v.Index(i).Set(sample(t.Elem(), filling))
			}
		}
	case reflect.Map:
		m := reflect.MakeMap(t)
		if !recurses(t.Elem(), filling) {
			m.SetMapIndex(sample(t.Key(), filling), sample(t.Elem(), filling))
		}
		v.Set(m)
	case reflect.String:
		v.SetString("x")
	case reflect.Bool:
		v.SetBool(true)
	case reflect.Int, reflect.Int8, reflect.Int16, reflect.Int32, reflect.Int64:
		v.SetInt(1)
	case reflect.Uint, reflect.Uint8, reflect.Uint16, reflect.Uint32, reflect.Uint64:
		v.SetUint(1)
	case reflect.Float32, reflect.Float64:
		v.SetFloat(1.5)
	case reflect.Interface:
		if t.NumMethod() == 0 {
			v.Set(reflect.ValueOf("x"))
		}
	}
	return v
}

// recurses reports whether t, through pointers and collections, is a struct
// already being filled on the current path.
func recurses(t reflect.Type, filling map[reflect.Type]bool) bool {
	for t.Kind() == reflect.Pointer || t.Kind() == reflect.Slice || t.Kind() == reflect.Array || t.Kind() == reflect.Map {
		t = t.Elem()
	}
	return filling[t]
}

// Swift renders route payloads as the menu bar test target's WirePayloads.
func Swift(payloads []RoutePayload) string {
	var b strings.Builder
	b.WriteString("// Code generated by wiregen from the Go wire structs. DO NOT EDIT.\n")
	b.WriteString("// Regenerate: go run ./cmd/genwire (daemon/). Drift fails TestSwiftPayloadsDrift.\n\n")
	b.WriteString("/// Each typed daemon route's response as encoding/json writes it, keyed by path.\n")
	b.WriteString("enum WirePayloads {\n")
	for _, variant := range []struct {
		name string
		body func(RoutePayload) []byte
	}{
		{"full", func(p RoutePayload) []byte { return p.Full }},
		{"empty", func(p RoutePayload) []byte { return p.Empty }},
	} {
		fmt.Fprintf(&b, "    static let %s: [String: String] = [\n", variant.name)
		for _, p := range payloads {
			fmt.Fprintf(&b, "        %q: #\"%s\"#,\n", p.Path, variant.body(p))
		}
		b.WriteString("    ]\n")
	}
	b.WriteString("}\n")
	return b.String()
}

// GenerateSwift renders WirePayloads for every typed route.
func GenerateSwift() (string, error) {
	payloads, err := RoutePayloads()
	if err != nil {
		return "", err
	}
	for _, p := range payloads {
		if strings.Contains(string(p.Full)+string(p.Empty), `"#`) {
			return "", fmt.Errorf("%s: payload would end its Swift raw string early", p.Path)
		}
	}
	return Swift(payloads), nil
}
