// Generate renders the .d.ts for the full wire-type set.
func Generate() string { return TypeScript(WireTypes()...) }

var timeType = reflect.TypeOf(time.Time{})

// TypeScript renders the given types as .d.ts interfaces. json tags drive
// names; omitempty becomes optional. Nested structs are emitted too.
func TypeScript(types ...any) string {
	fields := map[reflect.Type][]wireField{}
	var discover func(reflect.Type)
	discover = func(t reflect.Type) {
		if t == nil {
			return
		}
		switch t.Kind() {
		case reflect.Pointer, reflect.Slice, reflect.Array, reflect.Map:
			discover(t.Elem())
		case reflect.Struct:
			if t == timeType {
				return
			}
			if _, seen := fields[t]; seen {
				return
			}
			fields[t] = jsonFields(t)
			for _, f := range fields[t] {
				discover(f.typ)
			}
		}
	}
	for _, v := range types {
		discover(reflect.TypeOf(v))
	}
	names := typeNames(fields)
	emitted := map[reflect.Type]bool{}
	var out strings.Builder
	out.WriteString("// Code generated by wiregen from the Go wire structs. DO NOT EDIT.\n")
	out.WriteString("// Regenerate: go run ./cmd/genwire (daemon/). Drift fails TestWireTypesDrift.\n\n")
	var emit func(reflect.Type)
	emit = func(t reflect.Type) {
		if t == nil {
			return
		}
		for t.Kind() == reflect.Pointer || t.Kind() == reflect.Slice || t.Kind() == reflect.Array || t.Kind() == reflect.Map {
			t = t.Elem()
		}
		if t.Kind() != reflect.Struct || t == timeType || emitted[t] {
			return
		}
		emitted[t] = true
		for _, f := range fields[t] {
			emit(f.typ)
		}
		fmt.Fprintf(&out, "export interface %s {\n", names[t])
		for _, f := range fields[t] {
			tsType := tsTypeOf(f.typ, names)
			if f.omitEmpty {
				tsType = nonNullTSTypeOf(f.typ, names)
			}
			opt := ""
			if f.optional {
				opt = "?"
			}
			fmt.Fprintf(&out, "  %s%s: %s;\n", f.name, opt, tsType)
		}
		out.WriteString("}\n\n")
	}
	for _, v := range types {
		emit(reflect.TypeOf(v))
	}
	return out.String()
}

// Preserve familiar names unless distinct Go types would share a declaration.
// Resolve every name before rendering so references do not depend on root order.
func typeNames(fields map[reflect.Type][]wireField) map[reflect.Type]string {
	names := map[reflect.Type]string{}
	counts := map[string]int{}
	for t := range fields {
		counts[t.Name()]++
	}
	for t := range fields {
		name := t.Name()
		if counts[name] > 1 {
			pkg := []rune(path.Base(t.PkgPath()))
			if len(pkg) > 0 {
				pkg[0] = unicode.ToUpper(pkg[0])
			}
			name = string(pkg) + name
		}
		names[t] = name
	}
	counts = map[string]int{}
	for _, name := range names {
		counts[name]++
	}
	for t, name := range names {
		if counts[name] > 1 {
			// The full encoded package path distinguishes equal package basenames.
			names[t] = name + "_" + hex.EncodeToString([]byte(t.PkgPath()))
		}
	}
	return names
}

type wireField struct {
	name      string
	typ       reflect.Type
	optional  bool
	omitEmpty bool
	tagged    bool
	index     []int
}

// Follow encoding/json's promotion rules: the shallowest field wins, a
// tagged field wins ties, and ambiguous fields are absent from the payload.
func jsonFields(t reflect.Type) []wireField {
	var candidates []wireField
	ancestry := map[reflect.Type]bool{}
	var walk func(reflect.Type, []int, bool)
	walk = func(t reflect.Type, index []int, optional bool) {
		if ancestry[t] {
			return
		}
		ancestry[t] = true
		defer delete(ancestry, t)
		for i := 0; i < t.NumField(); i++ {
			f := t.Field(i)
			ft := f.Type
			if ft.Kind() == reflect.Pointer {
				ft = ft.Elem()
			}
			if !f.IsExported() && (!f.Anonymous || ft.Kind() != reflect.Struct) {
				continue
			}
			tag := f.Tag.Get("json")
			if tag == "-" {
				continue
			}
			name, opts, _ := strings.Cut(tag, ",")
			fieldIndex := append(append([]int(nil), index...), i)
			if f.Anonymous && name == "" && ft.Kind() == reflect.Struct {
				walk(ft, fieldIndex, optional || f.Type.Kind() == reflect.Pointer)
				continue
			}
			tagged := name != ""
			if name == "" {
				name = f.Name
			}
			omitEmpty := hasJSONOption(opts, "omitempty")
			candidates = append(candidates, wireField{
				name: name, typ: f.Type, optional: optional || omitEmpty,
				omitEmpty: omitEmpty, tagged: tagged, index: fieldIndex,
			})
		}
	}
	walk(t, nil, false)
	sort.SliceStable(candidates, func(i, j int) bool {
		a, b := candidates[i], candidates[j]
		if a.name != b.name {
			return a.name < b.name
		}
		if len(a.index) != len(b.index) {
			return len(a.index) < len(b.index)
		}
		return a.tagged && !b.tagged
	})
	var fields []wireField
	for i := 0; i < len(candidates); {
		end := i + 1
		for end < len(candidates) && candidates[end].name == candidates[i].name {
			end++
		}
		winner := candidates[i]
		if end == i+1 || len(winner.index) != len(candidates[i+1].index) || winner.tagged != candidates[i+1].tagged {
			fields = append(fields, winner)
		}
		i = end
	}
	sort.Slice(fields, func(i, j int) bool {
		a, b := fields[i].index, fields[j].index
		for k := 0; k < len(a) && k < len(b); k++ {
			if a[k] != b[k] {
				return a[k] < b[k]
			}
		}
		return len(a) < len(b)
	})
	return fields
}

func hasJSONOption(options, option string) bool {
	for _, value := range strings.Split(options, ",") {
		if value == option {
			return true
		}
	}
	return false
}

// Nil pointers, slices and maps encode as JSON null. omitempty removes only
// the outer nil value; collection elements and pointer targets keep their own
// nullability (a non-nil pointer to a nil slice still encodes as null).
func tsTypeOf(t reflect.Type, names map[reflect.Type]string) string {
	typ := nonNullTSTypeOf(t, names)
	switch t.Kind() {
	case reflect.Pointer, reflect.Slice, reflect.Map:
		if typ != "unknown" && !strings.HasSuffix(typ, " | null") {
			typ += " | null"
		}
	}
	return typ
}

func nonNullTSTypeOf(t reflect.Type, names map[reflect.Type]string) string {
	switch t.Kind() {
	case reflect.Pointer:
		return tsTypeOf(t.Elem(), names)
	case reflect.String:
		return "string"
	case reflect.Bool:
		return "boolean"
	case reflect.Int, reflect.Int32, reflect.Int64, reflect.Float64, reflect.Uint64, reflect.Int16, reflect.Uint32:
		return "number"
	case reflect.Slice, reflect.Array:
		elem := tsTypeOf(t.Elem(), names)
		if strings.Contains(elem, " | ") {
			elem = "(" + elem + ")"
		}
		return elem + "[]"
	case reflect.Map:
		return "Record<string, " + tsTypeOf(t.Elem(), names) + ">"
	case reflect.Struct:
		if t == timeType {
			return "string"
		}
		return names[t]
	default:
		return "unknown"
	}
}

// Names returns the sorted set of emitted type names (test hook).
func Names(ts string) []string {
	var out []string
	for _, line := range strings.Split(ts, "\n") {
		if strings.HasPrefix(line, "export interface ") {
			out = append(out, strings.TrimSuffix(strings.TrimPrefix(line, "export interface "), " {"))
		}
	}
	sort.Strings(out)
	return out
}

// JSONKeys returns every JSON key a struct (or its nested structs) emits,
// with nested keys flattened one level (e.g. "advisor.assessment"). The
// Swift mirror drift test uses this to prove the hand-written Codable types
// declare everything the daemon can send.
func JSONKeys(v any) []string {
	seen := map[string]bool{}
	var walk func(t reflect.Type, prefix string, depth int)
	walk = func(t reflect.Type, prefix string, depth int) {
		for t.Kind() == reflect.Pointer || t.Kind() == reflect.Slice {
			t = t.Elem()
		}
		if t.Kind() != reflect.Struct || t == timeType || depth > 2 {
			return
		}
		for i := 0; i < t.NumField(); i++ {
			f := t.Field(i)
			tag := f.Tag.Get("json")
			if tag == "-" {
				continue
			}
			name, _, _ := strings.Cut(tag, ",")
			if name == "" {
				name = f.Name
			}
			ft := f.Type
			for ft.Kind() == reflect.Pointer || ft.Kind() == reflect.Slice {
				ft = ft.Elem()
			}
			if ft.Kind() == reflect.Struct && ft != timeType && depth < 2 {
				// Nested object: recurse (keys are what the Swift side must
				// declare as a sub-struct; the parent key covers the leaf).
				walk(ft, prefix+name+".", depth+1)
			}
			seen[prefix+name] = true
		}
	}
	walk(reflect.TypeOf(v), "", 0)
	out := make([]string, 0, len(seen))
	for k := range seen {
		out = append(out, k)
	}
	sort.Strings(out)
	return out
}
